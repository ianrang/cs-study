def _run_check_cli(result: CheckResult, report: str) -> tuple[int, list[str]]:
    original_check_target = wiki_ingest.check_target
    original_generated_drift = wiki_ingest.generated_drift
    wiki_ingest.check_target = lambda *args, **kwargs: result
    wiki_ingest.generated_drift = lambda *args, **kwargs: ()
    try:
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            return_code = wiki_ingest.main(
                [
                    "check",
                    "--all",
                    "--target-root",
                    str(ROOT / "wiki"),
                    "--report",
                    report,
                ]
            )
    finally:
        wiki_ingest.check_target = original_check_target
        wiki_ingest.generated_drift = original_generated_drift
    return return_code, output.getvalue().splitlines()


